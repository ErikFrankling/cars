"""Spot-check prior report claims against this session's fetches. Usage: city_review_verify.py run_dir"""
import csv, gzip, html, json, pathlib, re, sys
d = pathlib.Path(sys.argv[1])
def T(n):
    raw = (d/(n+'.body')).read_bytes().decode('utf-8', 'replace')
    raw = re.sub(r'(?is)<(script|style|svg)\b.*?</\1>', ' ', raw)
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'(?s)<[^>]+>', ' ', raw)))
def grep(n, pat, c=170, k=4):
    t = T(n); print(f'-- {n} /{pat}/')
    for m in list(re.finditer(pat, t, re.I))[:k]: print('   ...', t[max(0, m.start()-c):m.end()+c])
