#!/usr/bin/env python3
"""Recipe step 2. Rebuild the district map from plain XML with each fix on a switch, so every issue is logged.

    step2_rebuild.py NAME [--no-lanes] [--no-speeds] [--no-chains] [--join-dist D] [--tls static|actuated]

Fixes, each from evidence and not from any flow:
  lanes, speeds: OSM of January 2019 and real loops (step2_map.py's patch)
  chains: a node with nothing but the road passing through it, left behind when bike and foot edges were
          removed. Lanes and speed on a short piece take the longer neighbour's, then --geometry.remove merges.
Signals are regenerated by netconvert for all junctions: they are invented in every version.
Writes district/NAME/net.net.xml, fixes.csv.
"""
import argparse
import collections
import re
import subprocess
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import *

D = B19 / 'district'


def main():
    p = argparse.ArgumentParser()
    p.add_argument('name')
    p.add_argument('--no-lanes', action='store_true')
    p.add_argument('--no-speeds', action='store_true')
    p.add_argument('--no-chains', action='store_true')
    p.add_argument('--short', type=float, default=25.0)
    p.add_argument('--join-dist', type=float)
    p.add_argument('--tls', default='actuated')
    p.add_argument('--cycle', type=int)
    p.add_argument('--contract', type=float, help='report 10: join across links whose built lanes are shorter than this, rebuild, repeat')
    p.add_argument('--cluster-max', type=float, default=70.0)
    p.add_argument('--per-node', action='store_true', help='report 10: one generated program per junction, not one over several')
    p.add_argument('--radii', action='store_true', help="report 19's junction geometry flags")
    p.add_argument('--smooth', action='store_true', help="report 19's polyline flags")
    a = p.parse_args()
    out = D / a.name
    out.mkdir(exist_ok=True)
    pfx = out / 'p'
    if not Path(str(pfx) + '.edg.xml').exists():
        subprocess.run(['netconvert', '--sumo-net-file', str(D / 'net0_cut.net.xml'), '--plain-output-prefix', str(pfx), '--no-internal-links', 'false', '--offset.disable-normalization', 'true', '--no-turnarounds', 'false'], check=True, capture_output=True)
    tree = etree.parse(str(pfx) + '.edg.xml', etree.XMLParser(huge_tree=True, resolve_entities=False, no_network=True))
    root = tree.getroot()
    edges = {e.get('id'): e for e in root.findall('edge')}
    fixes = []
    patch = {}
    if (D / 'patch.edg.xml').exists():
        for e in etree.parse(str(D / 'patch.edg.xml')).getroot().findall('edge'):
            patch[e.get('id')] = dict(e.attrib)
    touched = set()

    def set_lanes(e, n, why):
        old = len(e.findall('lane')) or int(e.get('numLanes', 1))
        if old == n:
            return
        ls = e.findall('lane')
        base = dict(ls[0].attrib) if ls else {}
        for l in ls:
            e.remove(l)
        e.set('numLanes', str(n))
        touched.add(e.get('id'))
        fixes.append((e.get('id'), why, f'lanes {old}->{n}'))

    def set_speed(e, v, why):
        old = float(e.get('speed', 0))
        for l in e.findall('lane'):
            l.attrib.pop('speed', None)
        if abs(old - v) > .05:
            e.set('speed', f'{v:.3f}')
            fixes.append((e.get('id'), why, f'speed {old * 3.6:.0f}->{v * 3.6:.0f}'))

    for k, at in patch.items():
        if k not in edges:
            continue
        if 'numLanes' in at and not a.no_lanes:
            set_lanes(edges[k], int(at['numLanes']), 'lanes_2019')
        if 'speed' in at and not a.no_speeds:
            set_speed(edges[k], float(at['speed']), 'speed_2019')

    if not a.no_chains:
        node_type = {n.get('id'): n.get('type', '') for n in etree.parse(str(pfx) + '.nod.xml').getroot().findall('node')}
        for _ in range(6):
            ins, outs = collections.defaultdict(list), collections.defaultdict(list)
            for k, e in edges.items():
                outs[e.get('from')].append(k)
                ins[e.get('to')].append(k)
            changed = 0
            def length(k):
                e = edges[k]
                if e.get('length'):
                    return float(e.get('length'))
                c = np.array([list(map(float, x.split(',')))[:2] for x in e.get('shape', '0,0 0,0').split()])
                return float(np.linalg.norm(np.diff(c, axis=0), axis=1).sum())
            for n, t in node_type.items():
                if t in ('traffic_light', 'dead_end'):
                    continue
                ii, oo = ins[n], outs[n]
                pairs = []
                if len(ii) == 1 and len(oo) == 1:
                    pairs = [(ii[0], oo[0])]
                elif len(ii) == 2 and len(oo) == 2:
                    fr = {edges[k].get('from'): k for k in ii}
                    to = {edges[k].get('to'): k for k in oo}
                    if set(fr) == set(to) and len(fr) == 2:
                        ks = list(fr)
                        pairs = [(fr[ks[0]], to[ks[1]]), (fr[ks[1]], to[ks[0]])]
                for u, v in pairs:
                    lu, lv = length(u), length(v)
                    if min(lu, lv) >= a.short:
                        continue
                    s, l_ = (u, v) if lu < lv else (v, u)
                    nl = len(edges[l_].findall('lane')) or int(edges[l_].get('numLanes', 1))
                    ns = len(edges[s].findall('lane')) or int(edges[s].get('numLanes', 1))
                    if nl != ns:
                        set_lanes(edges[s], nl, f'chain_short_{min(lu, lv):.0f}m')
                        changed += 1
                    if edges[s].get('speed') != edges[l_].get('speed'):
                        set_speed(edges[s], float(edges[l_].get('speed')), 'chain_speed')
                        changed += 1
                    # netconvert merges only pieces that are alike in everything: copy the rest too
                    for at in ('priority', 'type', 'name', 'width', 'sidewalkWidth', 'bikeLaneWidth', 'allow', 'disallow', 'spreadType'):
                        if edges[l_].get(at) != edges[s].get(at):
                            if edges[l_].get(at) is None:
                                edges[s].attrib.pop(at, None)
                            else:
                                edges[s].set(at, edges[l_].get(at))
                            changed += 1
                    ll, sl = edges[l_].findall('lane'), edges[s].findall('lane')
                    if [dict(x.attrib) for x in ll] != [dict(x.attrib) for x in sl]:
                        for x in sl:
                            edges[s].remove(x)
                        for x in ll:
                            y = etree.SubElement(edges[s], 'lane')
                            for kk, vv in x.attrib.items():
                                y.set(kk, vv)
                        changed += 1
            if not changed:
                break
    # listed roundabouts crash netconvert once their nodes are joined; guessing them gives the same priorities
    for r in root.findall('roundabout'):
        root.remove(r)
    tree.write(str(pfx) + '_fixed.edg.xml')
    # connections are recomputed on every touched edge and on those into it; everywhere else they stay
    con = etree.parse(str(pfx) + '.con.xml', etree.XMLParser(huge_tree=True, resolve_entities=False, no_network=True)).getroot()
    kept = 0
    by_edge = collections.defaultdict(set)
    for c in con:
        if c.tag == 'connection':
            by_edge[c.get('from')].add(int(c.get('fromLane', -1)))
    for k, e in edges.items():
        n = len(e.findall('lane')) or int(e.get('numLanes', 1))
        if by_edge[k] and not all(i in by_edge[k] for i in range(n)) and k not in touched:
            touched.add(k)
            fixes.append((k, 'lane_with_no_way_on', 'connections recomputed'))
    # netconvert guesses nothing for an edge with any listed connection, so a from-edge is recomputed whole
    redo = set(touched) | {c.get('from') for c in con if c.tag == 'connection' and c.get('to') in touched}
    for c in list(con):
        if c.tag == 'connection' and c.get('from') in redo:
            con.remove(c)
        elif c.tag == 'crossing' or c.tag == 'walkingArea':
            con.remove(c)
        else:
            kept += 1
    etree.ElementTree(con).write(str(pfx) + '_fixed.con.xml')
    nod = etree.parse(str(pfx) + '.nod.xml', etree.XMLParser(huge_tree=True, resolve_entities=False, no_network=True))
    if a.per_node:
        n_shared = 0
        for n in nod.getroot().findall('node'):
            if n.get('tl') and n.get('tl') != n.get('id'):
                n_shared += 1
            n.attrib.pop('tl', None)
        print('nodes taken out of shared controllers', n_shared)
    xy = {n.get('id'): (float(n.get('x')), float(n.get('y'))) for n in nod.getroot().findall('node')}
    parent = {k: k for k in xy}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def build(tag):
        r = nod.getroot()
        for j in r.findall('join'):
            r.remove(j)
        groups = collections.defaultdict(list)
        for k in xy:
            groups[find(k)].append(k)
        for g in groups.values():
            if len(g) > 1:
                etree.SubElement(r, 'join', nodes=' '.join(sorted(g)))
        nod.write(str(pfx) + '_fixed.nod.xml')
        # a joined junction loses the listed turns over the swallowed links, so it gets all its turns afresh
        joined = {m for g in groups.values() if len(g) > 1 for m in g}
        c2 = etree.fromstring(etree.tostring(con))
        for c in list(c2):
            if c.tag == 'connection' and c.get('from') in edges and edges[c.get('from')].get('to') in joined:
                c2.remove(c)
        etree.ElementTree(c2).write(str(pfx) + '_build.con.xml')
        cmd = ['netconvert', '-n', str(pfx) + '_fixed.nod.xml', '-e', str(pfx) + '_fixed.edg.xml', '-x', str(pfx) + '_build.con.xml', '-t', str(pfx) + '.typ.xml', '--no-internal-links', 'false', '--offset.disable-normalization', 'true', '--no-turnarounds', 'false', '--geometry.remove', 'true', '--tls.default-type', a.tls, '--output.original-names', 'false', '--remove-edges.isolated', 'true', '--junctions.corner-detail', '5', '--roundabouts.guess', 'true', '-o', str(out / 'net.net.xml')]
        if a.join_dist:
            cmd += ['--junctions.join', 'true', '--junctions.join-dist', str(a.join_dist)]
        if a.cycle:
            cmd += ['--tls.cycle.time', str(a.cycle)]
        if a.radii:
            cmd += ['--default.junctions.radius', '10', '--junctions.small-radius', '8', '--junctions.limit-turn-speed', '2.5']
        if a.smooth:
            cmd += ['--geometry.min-radius', '12', '--geometry.min-radius.fix', 'true', '--geometry.max-angle', '30', '--geometry.max-angle.fix', 'true']
        r = subprocess.run(cmd, capture_output=True, text=True)
        print(tag, r.stderr[-600:] if r.returncode else '\n'.join(l for l in r.stderr.splitlines() if 'total messages' in l)[:900])
        r.check_returncode()

    build('first pass')
    for it in range(6 if a.contract else 0):
        (out / 'net.pkl').unlink(missing_ok=True)
        n = read_net(out / 'net.net.xml', out / 'net.pkl')
        groups = collections.defaultdict(list)
        for k in xy:
            groups[find(k)].append(k)
        node_of = {}
        for k, g in groups.items():
            for m in g:
                node_of[m] = k
        new = 0
        for k, v in n['edges'].items():
            cl = car_lanes(v)
            if not cl or min(l['length'] for l in cl) >= a.contract:
                continue
            # ids of joined nodes are 'cluster_a_b...' : take any member known to us
            def member(j):
                if j in xy:
                    return j
                for m in re.split(r'_', j.replace('cluster_', '')):
                    if m in xy:
                        return m
                return None
            u, w = member(v['start']), member(v['end'])
            if u is None or w is None:
                continue
            ru, rw = find(u), find(w)
            if ru == rw:
                continue
            pts = np.array([xy[m] for m in groups[ru] + groups[rw]])
            if np.linalg.norm(pts.max(axis=0) - pts.min(axis=0)) > a.cluster_max:
                continue
            parent[rw] = ru
            groups[ru] += groups[rw]
            groups[rw] = []
            new += 1
        print('contract pass', it, 'joins', new)
        if not new:
            break
        build(f'pass {it}')
    (out / 'net.pkl').unlink(missing_ok=True)
    pd.DataFrame(fixes, columns=['edge', 'why', 'change']).to_csv(out / 'fixes.csv', index=False)
    print('fixes', collections.Counter(re.sub(r'_short.*', '_short', f[1]) for f in fixes).most_common(), 'connections kept', kept, 'edges touched', len(touched), 'edges recomputed', len(redo))
    n = read_net(out / 'net.net.xml', out / 'net.pkl')
    e = {k: v for k, v in n['edges'].items() if car_lanes(v)}
    short = sum(car_lanes(v)[0]['length'] < 7.5 for v in e.values())
    lane_out = collections.Counter((c[0], c[2]) for c in n['conns'])
    conn_out = collections.Counter(c[0] for c in n['conns'])
    no_exit = sum(1 for k, v in e.items() for l in car_lanes(v) if conn_out[k] and lane_out[(k, l['index'])] == 0)
    print('edges', len(e), 'shorter than 7.5 m', short, 'lanes with no way on', no_exit, 'tls', n['tls'])


if __name__ == '__main__':
    main()
